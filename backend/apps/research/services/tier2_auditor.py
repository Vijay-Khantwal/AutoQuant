"""
research/services/tier2_auditor.py
Nemotron 120B — Chief Risk Officer auditor (Tier 2 LLM).
"""
import json
import logging

from openai import OpenAI
from django.conf import settings

logger = logging.getLogger(__name__)

SYSTEM_INSTRUCTION = """
You are a Senior Quantitative Equity Risk Officer for the Indian Stock Market (NSE).
Your task is to conduct an EXHAUSTIVE and STRICT risk audit on a candidate swing trade.
You must deeply analyze the provided fundamentals and news brief. Do not approve a stock lightly.

Hard Veto Rules (Reject immediately if any are true):
1. Insolvency Risk: Debt-to-Equity > 2.0 (except Banks/NBFCs).
2. Negative Cash Flows: Negative operating cash flow coupled with high debt.
3. Severe Governance / Regulatory Hazards: Active SEBI investigations, fraud, or promoter insider controversies mentioned in the news.

Decision Standard:
- APPROVE: Only if fundamentals are solid, debt is manageable, and sentiment supports a stable 15-day hold period.
- REJECT: If there is ANY ambiguity in governance, solvency, or if the news sentiment is overwhelmingly negative.

You MUST respond ONLY with a valid JSON object matching the requested schema. Do NOT wrap it in markdown blockquotes.
"""


def audit_stock(dossier: dict, news_brief: str) -> dict:
    """
    Tier 2: runs the Nemotron auditor and returns a parsed verdict dict.
    Raises on unrecoverable errors; returns error dict on JSON parse failure.
    """
    ticker = dossier["metadata"]["ticker"]
    prompt = f"""
Evaluate the following equity dossier and output your final audit verdict.

=== CANDIDATE DOSSIER ===
Ticker: {ticker}
LTP: ₹{dossier['quantitative_inputs']['ltp']}
ML Win Probability: {dossier['quantitative_inputs']['ml_win_probability'] * 100:.2f}%
Percentile Rank: Top {100 - dossier['quantitative_inputs']['percentile_rank']:.1f}%

--- FUNDAMENTALS & VALUATION ---
{json.dumps(dossier['fundamentals'], indent=2)}

--- TIER 1 NEWS BRIEF (DISTILLED FACTS) ---
{news_brief}

Output your evaluation strictly in the following JSON format:
{{
  "ticker": "{ticker}",
  "decision": "APPROVE" or "REJECT",
  "confidence_score": 0.00,
  "risk_flags": ["<string explaining flag, or empty if none>"],
  "fundamental_summary": "<brief assessment of debt, cashflow, and valuation>",
  "news_and_sentiment_summary": "<brief synthesis of the news brief>",
  "final_rationale": "<concise 2-sentence rationale for approval or rejection>",
  "recommended_allocation_inr": <number: 0 if REJECT, up to 20000 if APPROVE>
}}
"""
    try:
        logger.info("  [Tier 2] Auditing %s...", ticker)
        client = OpenAI(base_url=settings.NIM_BASE_URL, api_key=settings.NVIDIA_API_KEY)
        response = client.chat.completions.create(
            model=settings.NVIDIA_REASONING_MODEL,
            messages=[
                {"role": "system", "content": SYSTEM_INSTRUCTION},
                {"role": "user", "content": prompt}
            ],
            temperature=0.0,
            max_tokens=8000,
        )
        content = response.choices[0].message.content
        if not content:
            raise ValueError("No response generated by Tier 2 LLM.")
        content = content.strip()
        if content.startswith("```json"):
            content = content[7:]
        elif content.startswith("```"):
            content = content[3:]
        
        content = content.strip()
        if content.endswith("```"):
            content = content[:-3].strip()
        
        return json.loads(content)
    except Exception as exc:
        logger.error("Tier 2 auditor failed for %s: %s", ticker, exc)
        return {
            "ticker": ticker,
            "decision": "REJECT",
            "confidence_score": 0.0,
            "risk_flags": [f"LLM Parsing Error: {exc}"],
            "fundamental_summary": "",
            "news_and_sentiment_summary": "",
            "final_rationale": "Audit failed due to error.",
            "recommended_allocation_inr": 0,
        }
